        }
        if (($null -ne $userAttributes) -and [System.IO.Directory]::Exists($userProfile)) {
            [System.IO.File]::SetAttributes($userProfile, $userAttributes)
        }
    }
    Remove-Item -Recurse -Force $h12 -ErrorAction SilentlyContinue
