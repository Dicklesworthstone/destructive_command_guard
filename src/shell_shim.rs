//! PATH shims for shells that do not run through an agent hook.
//!
//! Hooked tools (Claude Code, OpenCode, Codex, ...) are guarded by their
//! `PreToolUse`/plugin integration. A plain shell started by a custom agent
//! runtime, a cron job, or a script is not: it executes `rm` directly from
//! `PATH`. `dcg install --shell-shim` writes small wrappers for the guarded
//! command names into a bin directory. Each wrapper asks `dcg test` for a
//! verdict on the reconstructed command line and only then execs the real
//! binary.
//!
//! This is deliberately a narrow safety rail, not a replacement for hooks:
//! absolute paths (`/bin/rm`), shell builtins, functions and aliases bypass
//! `PATH` shims, and `dcg test` sees the flattened command line rather than a
//! heredoc body. See `docs/shell-shim.md`.

use std::error::Error;
use std::fs;
use std::path::{Path, PathBuf};

pub const SHIM_MARKER: &str = "dcg-shell-shim";

/// Commands with shims by default. Deliberately short: every shim adds one
/// dcg verdict call to that command, so the list stays focused on destructive
/// filesystem operations.
pub const SHIM_COMMANDS: &[&str] = &[
    "rm", "mv", "cp", "chmod", "chown", "dd", "truncate", "shred",
];

const SHIM_TEMPLATE: &str = r#"#!/usr/bin/env bash
# dcg-shell-shim: generated by `dcg install --shell-shim` — do not edit.
# Checks the command with dcg before calling the real binary. Remove with
# `dcg uninstall --shell-shim`. Docs: docs/shell-shim.md
set -u
DCG_BIN=__DCG_BIN__
SHIM_DIR=__SHIM_DIR__
CMD=__CMD__

# Find the real binary by skipping this shim directory. Resolving at run time
# keeps the shim correct when PATH changes between sessions.
IFS=: read -r -a dcg_dirs <<< "${PATH:-}"
real=""
for d in "${dcg_dirs[@]}"; do
  [ -n "$d" ] || continue
  [ "${d%/}" = "${SHIM_DIR%/}" ] && continue
  [ -x "$d/$CMD" ] || continue
  [ "$d/$CMD" = "$0" ] && continue
  real="$d/$CMD"
  break
done
if [ -z "$real" ]; then
  printf 'dcg-shell-shim: real %s not found on PATH\n' "$CMD" >&2
  exit 127
fi

# %q keeps quoted operands with spaces as one operand in the verdict input.
{
  printf '%s' "$CMD"
  printf ' %q' "$@"
  printf '\n'
} | "$DCG_BIN" test --dialect posix --robot --no-color -f json --stdin >/dev/null 2>&1
verdict=$?
case "$verdict" in
  0) exec "$real" "$@" ;;
  1)
    printf 'dcg-shell-shim: BLOCKED %s %s (dcg deny)\n' "$CMD" "$*" >&2
    exit 126
    ;;
  2)
    printf 'dcg-shell-shim: warning from dcg for %s %s; proceeding\n' "$CMD" "$*" >&2
    exec "$real" "$@"
    ;;
  *)
    printf 'dcg-shell-shim: dcg could not evaluate %s (exit %s); blocked\n' "$CMD" "$verdict" >&2
    exit 125
    ;;
esac
"#;

/// Shell single-quote a value embedded in the generated script.
fn quote_single(value: &str) -> String {
    format!("'{}'", value.replace('\'', "'\\''"))
}

pub fn shim_script(dcg: &Path, shim_dir: &Path, cmd: &str) -> String {
    SHIM_TEMPLATE
        .replace("__DCG_BIN__", &quote_single(&dcg.display().to_string()))
        .replace(
            "__SHIM_DIR__",
            &quote_single(&shim_dir.display().to_string()),
        )
        .replace("__CMD__", &quote_single(cmd))
}

/// Install destination: `$XDG_BIN_HOME`, otherwise `~/.local/bin`.
fn shim_dir() -> Result<PathBuf, Box<dyn Error>> {
    if let Some(dir) = std::env::var_os("XDG_BIN_HOME").filter(|v| !v.is_empty()) {
        return Ok(PathBuf::from(dir));
    }
    let home =
        crate::config::home_dir().ok_or("could not resolve home directory; set XDG_BIN_HOME")?;
    Ok(home.join(".local").join("bin"))
}

fn marked(path: &Path) -> Result<bool, Box<dyn Error>> {
    match fs::read_to_string(path) {
        Ok(content) => Ok(content.contains(SHIM_MARKER)),
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => Ok(false),
        Err(error) => Err(format!("could not read {}: {error}", path.display()).into()),
    }
}

pub fn install(force: bool) -> Result<(), Box<dyn Error>> {
    let dir = shim_dir()?;
    let executable = std::env::current_exe()?;
    if !executable.is_absolute() || !executable.is_file() {
        return Err("running dcg executable path is not an absolute regular file".into());
    }

    fs::create_dir_all(&dir)?;
    let mut written = 0;
    for cmd in SHIM_COMMANDS {
        let path = dir.join(cmd);
        if let Ok(metadata) = fs::symlink_metadata(&path) {
            let is_symlink = metadata.file_type().is_symlink();
            let ours = marked(&path)?;
            if !ours && !force {
                return Err(format!(
                    "{} exists and was not generated by dcg; move it aside first \
                     (or pass --force to overwrite it)",
                    path.display()
                )
                .into());
            }
            if is_symlink && !force {
                return Err(format!(
                    "{} is a symlink; pass --force to replace it",
                    path.display()
                )
                .into());
            }
        }
        fs::write(&path, shim_script(&executable, &dir, cmd))?;
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            let mut permissions = fs::metadata(&path)?.permissions();
            permissions.set_mode(0o755);
            fs::set_permissions(&path, permissions)?;
        }
        written += 1;
    }

    println!("Installed {written} dcg shell shims in {}", dir.display());
    println!("Put this directory before the system bin directories in PATH:");
    println!("  export PATH=\"{}:$PATH\"", dir.display());
    println!("Remove them later with `dcg uninstall --shell-shim`.");
    Ok(())
}

pub fn uninstall() -> Result<(), Box<dyn Error>> {
    let dir = shim_dir()?;
    if !dir.exists() {
        println!("No dcg shell shims in {}", dir.display());
        return Ok(());
    }
    let mut removed = 0;
    let mut kept = 0;
    for cmd in SHIM_COMMANDS {
        let path = dir.join(cmd);
        match fs::symlink_metadata(&path) {
            Ok(metadata) if metadata.file_type().is_file() => {}
            Ok(_) => continue,
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => continue,
            Err(error) => {
                return Err(format!("could not inspect {}: {error}", path.display()).into());
            }
        }
        if marked(&path)? {
            fs::remove_file(&path)?;
            removed += 1;
        } else {
            println!("Kept user-owned {}", path.display());
            kept += 1;
        }
    }
    println!(
        "Removed {removed} dcg shell shims from {} (kept {kept} other files).",
        dir.display()
    );
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn script_carries_marker_command_and_absolute_dcg_path() {
        let script = shim_script(
            Path::new("/opt/dcg/bin/dcg"),
            Path::new("/home/u/.local/bin"),
            "rm",
        );
        assert!(script.contains(SHIM_MARKER));
        assert!(script.contains("CMD='rm'"));
        assert!(script.contains("DCG_BIN='/opt/dcg/bin/dcg'"));
        assert!(script.contains("SHIM_DIR='/home/u/.local/bin'"));
        assert!(script.contains("--stdin"));
        assert!(script.contains("exit 126"));
    }

    #[test]
    fn quoting_handles_single_quotes_in_paths() {
        assert_eq!(quote_single("/tmp/it's here"), "'/tmp/it'\\''s here'");
        let script = shim_script(Path::new("/tmp/it's here/dcg"), Path::new("/tmp/bin"), "cp");
        assert!(script.contains("DCG_BIN='/tmp/it'\\''s here/dcg'"));
    }

    #[test]
    fn guarded_command_list_has_no_duplicates() {
        let mut unique = SHIM_COMMANDS.to_vec();
        unique.sort_unstable();
        unique.dedup();
        assert_eq!(unique.len(), SHIM_COMMANDS.len());
    }
}
